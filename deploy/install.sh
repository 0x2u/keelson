#!/bin/sh
# Installs the Keelson dashboard with Docker Compose, then tells you where to open it and the one-time token the first visit asks for.
#
#   curl -fsSL https://github.com/0x2u/keelson/releases/latest/download/install.sh | sudo sh
#   curl -fsSL https://github.com/0x2u/keelson/releases/latest/download/install.sh | sudo sh -s -- --domain keelson.example.com
#   sh deploy/install.sh [--dir /opt/keelson] [--domain keelson.example.com] [--version v0.1.0]
#
#   --dir DIR        where the compose files live (default /opt/keelson)
#   --domain NAME    serve https://NAME with a certificate Caddy gets and renews by itself. NAME must already point at this
#                    machine and ports 80 and 443 must be open. Without it the dashboard listens on 127.0.0.1:3000 only.
#   --version TAG    the release to run (default latest). The compose files are taken from that same release.
#
# The compose files are not embedded: from a checkout the script uses the ones next to it, otherwise it downloads them from the
# release it installs (https://github.com/0x2u/keelson/releases), so image and compose file always match.
# Safe to run again; to update, run it with --version <release> (same command for every install). It copies the database to
# DIR/backups first, pulls the images, applies the files and restarts only what changed. An existing .env is kept as it is;
# only a value you pass again (--version, --domain) is changed in it. Nothing secret is written: .env holds the version and
# the domain. The master key is generated by the dashboard in its data volume; you download it from the setup page.
#
# Testing hooks (not for normal use): KEELSON_IMAGE=<image without tag> runs a local image (nothing is pulled),
# KEELSON_PORT=<port> publishes it on another port, KEELSON_RELEASE_URL=<base url> fetches the files from there (file:// works).
set -eu
umask 077

repo=0x2u/keelson
dir=/opt/keelson
domain=
version=

say() { printf '%s\n' "$*"; }
die() { printf 'keelson install: %s\n' "$*" >&2; exit 1; }
usage() { say "usage: install.sh [--dir /opt/keelson] [--domain keelson.example.com] [--version v0.1.0]"; }

while [ $# -gt 0 ]; do
  case $1 in
    --dir) [ $# -ge 2 ] || die "--dir needs a directory"; dir=$2; shift 2 ;;
    --domain) [ $# -ge 2 ] || die "--domain needs a name"; domain=$2; shift 2 ;;
    --version) [ $# -ge 2 ] || die "--version needs a release such as v0.1.0, or latest"; version=$2; shift 2 ;;
    -h | --help) usage; exit 0 ;;
    *) die "unknown option $1 (try --help)" ;;
  esac
done

domain=$(printf '%s' "$domain" | tr '[:upper:]' '[:lower:]')
# A bare 0.1.0 is the release v0.1.0: that is how the images are tagged.
case $version in [0-9]*) version=v$version ;; esac
case $version in *[!A-Za-z0-9_.-]*) die "'$version' is not a release tag such as v0.1.0" ;; esac
case $domain in
  "") ;;
  *[!A-Za-z0-9.-]* | .* | *. | -* | *..*) die "'$domain' is not a domain name: give the name only, like keelson.example.com (no https://, no port)" ;;
  *.*) ;;
  *) die "'$domain' is not a domain name: it needs at least one dot" ;;
esac

# Docker, with the compose plugin recent enough for the files (2.24 reads `!reset` and an optional env_file).
command -v docker >/dev/null 2>&1 || die "docker is not installed. Install Docker Engine first: https://docs.docker.com/engine/install/"
docker info >/dev/null 2>&1 || die "cannot talk to docker: is it running, and may this user use it? (try with sudo)"
compose_version=$(docker compose version --short 2>/dev/null) || die "docker compose is missing: install the compose plugin: https://docs.docker.com/compose/install/"
compose_version=${compose_version#v}
major=${compose_version%%.*}
minor=${compose_version#*.}
minor=${minor%%.*}
case $major$minor in *[!0-9]* | "") die "cannot read the docker compose version ($compose_version)" ;; esac
if [ "$major" -lt 2 ] || { [ "$major" -eq 2 ] && [ "$minor" -lt 24 ]; }; then
  die "docker compose $compose_version is too old: 2.24 or newer is needed"
fi

mkdir -p "$dir" 2>/dev/null || die "cannot create $dir: run this as root (sudo sh) or choose another place with --dir"
dir=$(cd "$dir" && pwd)
tmp=$(mktemp -d "$dir/.install.XXXXXX") || die "cannot write in $dir"
trap 'rm -rf "$tmp"' EXIT INT TERM

version_asked=$version
existing=
[ ! -f "$dir/.env" ] || existing=1
env_get() { sed -n "s/^$1=//p" "$dir/.env" 2>/dev/null | tail -1; }
env_set() {
  { grep -v "^$1=" "$dir/.env" 2>/dev/null || true; printf '%s=%s\n' "$1" "$2"; } >"$tmp/env"
  mv "$tmp/env" "$dir/.env"
}

prev=$(env_get KEELSON_VERSION)

# The domain in effect: the one asked for now, else the one a previous run saved.
[ -n "$domain" ] || domain=$(env_get KEELSON_DOMAIN)
if [ -z "$version" ]; then
  version=$(env_get KEELSON_VERSION)
  case $version in
    "" | latest) ;;
    *) [ "$existing" != 1 ] || say "Pinned to $version (the version in .env). To update: re-run with --version <new version>" ;;
  esac
fi
[ -n "$version" ] || version=latest

# Where the compose files come from.
here=
if [ -f "$0" ] && [ "$(basename "$0")" = install.sh ] && [ -f "$(dirname "$0")/compose.yaml" ]; then here=$(cd "$(dirname "$0")" && pwd); fi
if [ -n "${KEELSON_RELEASE_URL:-}" ]; then
  base=$KEELSON_RELEASE_URL
elif [ "$version" = latest ]; then
  base=https://github.com/$repo/releases/latest/download
else
  base=https://github.com/$repo/releases/download/$version
fi

fetch() { # file
  if [ -n "$here" ] && [ -z "${KEELSON_RELEASE_URL:-}" ]; then
    cp "$here/$1" "$tmp/$1"
  elif command -v curl >/dev/null 2>&1; then
    curl -fsSL "$base/$1" -o "$tmp/$1" || die "cannot download $base/$1 (is '$version' a published release?)"
  elif command -v wget >/dev/null 2>&1; then
    wget -qO "$tmp/$1" "$base/$1" || die "cannot download $base/$1 (is '$version' a published release?)"
  else
    die "neither curl nor wget is installed"
  fi
}

# Put a file in place; a copy that differs from the one there replaces it and the old one is kept beside it as NAME.old.
place() { # file
  fetch "$1"
  if [ -f "$dir/$1" ] && ! cmp -s "$tmp/$1" "$dir/$1"; then
    cp "$dir/$1" "$dir/$1.old"
    say "replaced $dir/$1 (the previous one is $1.old)"
  fi
  chmod 644 "$tmp/$1"
  mv "$tmp/$1" "$dir/$1"
}

place compose.yaml
if [ -n "$domain" ]; then
  place compose.tls.yaml
  place Caddyfile
fi

# .env: choices only. Created on the first run; later only a value passed again (or a testing hook) is changed.
if [ ! -f "$dir/.env" ]; then
  say "writing $dir/.env"
  : >"$dir/.env"
  env_set KEELSON_VERSION "$version"
fi
[ "$(env_get KEELSON_VERSION)" = "$version" ] || env_set KEELSON_VERSION "$version"
if [ -n "$domain" ]; then
  [ "$(env_get KEELSON_DOMAIN)" = "$domain" ] || env_set KEELSON_DOMAIN "$domain"
  [ "$(env_get COMPOSE_FILE)" = compose.yaml:compose.tls.yaml ] || env_set COMPOSE_FILE compose.yaml:compose.tls.yaml
fi
[ -z "${KEELSON_IMAGE:-}" ] || [ "$(env_get KEELSON_IMAGE)" = "$KEELSON_IMAGE" ] || env_set KEELSON_IMAGE "$KEELSON_IMAGE"
[ -z "${KEELSON_PORT:-}" ] || [ "$(env_get KEELSON_PORT)" = "$KEELSON_PORT" ] || env_set KEELSON_PORT "$KEELSON_PORT"
chmod 600 "$dir/.env"

cd "$dir"

# Who listens on a TCP port: prints the process if ss or lsof can tell, nothing otherwise. Returns 0 when the port is taken.
port_holder() { # port
  held=
  if command -v ss >/dev/null 2>&1; then
    held=$(ss -ltnpH "sport = :$1" 2>/dev/null | head -n 1 || true)
    [ -z "$held" ] || { say "  port $1 is held by: ${held##* }"; return 0; }
  elif command -v lsof >/dev/null 2>&1; then
    held=$(lsof -nP -iTCP:"$1" -sTCP:LISTEN 2>/dev/null | sed -n 2p || true)
    [ -z "$held" ] || { say "  port $1 is held by: ${held%% *}"; return 0; }
  fi
  return 1
}
# A port this compose project already publishes is fine: `up` keeps it.
preflight() {
  busy=
  if [ -n "$domain" ]; then
    if [ -z "$(docker compose ps -q caddy 2>/dev/null || true)" ]; then
      for p in 80 443; do port_holder "$p" && busy="$busy $p"; done
    fi
  elif [ -z "$(docker compose ps -q dashboard 2>/dev/null || true)" ]; then
    p=$(env_get KEELSON_PORT)
    p=${p:-${KEELSON_PORT:-3000}}
    port_holder "$p" && busy="$busy $p"
  fi
  [ -z "$busy" ] || die "port${busy} already in use (see above). Stop what uses it, or free it, and run this again."
}
preflight
[ -z "$domain" ] || say "The name $domain must point at this machine, or no certificate can be issued."

# Safety copy of the database before an update: the new version migrates it forward and cannot migrate it back. Best effort.
dbcopy=
if [ "$existing" = 1 ] && [ -z "$(env_get KEELSON_IMAGE)" ] && [ -n "$(docker compose ps -q dashboard 2>/dev/null || true)" ]; then
  stamp=$(date +%Y%m%d-%H%M%S)
  mkdir -p "$dir/backups"
  chmod 700 "$dir/backups"
  if docker compose exec -T dashboard node -e 'const{DatabaseSync}=require("node:sqlite");const d=new DatabaseSync("/data/dashboard.db");d.exec("VACUUM INTO \x27/data/.upgrade-copy.db\x27")' >/dev/null 2>&1 &&
    docker compose cp dashboard:/data/.upgrade-copy.db "$dir/backups/dashboard-$stamp.db" >/dev/null 2>&1; then
    chmod 600 "$dir/backups/dashboard-$stamp.db"
    dbcopy=$dir/backups/dashboard-$stamp.db
    say "database copied to $dbcopy"
    # Keep the last 3.
    # shellcheck disable=SC2012
    ls -1t "$dir"/backups/dashboard-*.db 2>/dev/null | sed -n '4,$p' | while IFS= read -r old; do rm -f "$old"; done
  else
    say "warning: could not copy the database before the update (continuing). Download a backup from Settings, Backup if you have not."
  fi
  docker compose exec -T dashboard rm -f /data/.upgrade-copy.db >/dev/null 2>&1 || true
fi

if [ -z "$(env_get KEELSON_IMAGE)" ]; then
  say "pulling Keelson $version"
  docker compose pull || die "could not pull the images: is $version a published release, and can this machine reach ghcr.io?"
fi
say "starting"
if ! docker compose up -d --wait --wait-timeout 180; then
  docker compose ps >&2 || true
  docker compose logs --no-color --tail 30 >&2 || true
  if [ -n "$domain" ] && [ -z "$(docker compose ps --status running -q caddy 2>/dev/null || true)" ]; then
    say "Caddy (the HTTPS front) is not running: see its log above. Check that ports 80 and 443 are free and open." >&2
  fi
  if [ "$existing" = 1 ] && [ -n "$prev" ] && [ "$prev" != "$version" ]; then
    {
      say ""
      say "To go back to $prev: the new version may already have migrated the database forward, so run the old version on the copy taken before:"
      if [ -n "$dbcopy" ]; then
        say "  cd $dir && docker compose down && docker run --rm -v keelson_data:/data -v $dir/backups:/b alpine sh -c 'rm -f /data/dashboard.db-wal /data/dashboard.db-shm && cp /b/${dbcopy##*/} /data/dashboard.db && chown 1000:1000 /data/dashboard.db'"
      else
        say "  no copy was made: use the backup you downloaded from Settings, Backup."
      fi
      say "  then:  curl -fsSL https://github.com/$repo/releases/download/$prev/install.sh | sudo sh -s -- --version $prev"
    } >&2
  fi
  if [ -n "$domain" ] && [ -z "$(docker compose ps --status running -q caddy 2>/dev/null || true)" ]; then
    die "Caddy failed to start. Fix it and run this again."
  fi
  die "the dashboard did not become healthy (log above). Fix it and run this again."
fi

# Where to open it.
if [ -n "$domain" ]; then
  url=https://$domain
else
  port=$(env_get KEELSON_PORT)
  url=http://localhost:${port:-3000}
fi

# The token the first visit asks for: the last one this start of the container logged (every start prints a new one).
token_line=
cid=$(docker compose ps -q dashboard)
started=$(docker inspect -f '{{.State.StartedAt}}' "$cid" 2>/dev/null || true)
tries=0
while [ "$tries" -lt 15 ]; do
  if [ -n "$started" ]; then
    token_line=$(docker compose logs --no-color --since "$started" dashboard 2>/dev/null | sed -n 's/.*\(Keelson setup token: .*\)$/\1/p' | tail -1)
  else
    token_line=$(docker compose logs --no-color dashboard 2>/dev/null | sed -n 's/.*\(Keelson setup token: .*\)$/\1/p' | tail -1)
  fi
  [ -z "$token_line" ] || break
  tries=$((tries + 1))
  sleep 1
done

say ""
if [ "$existing" = 1 ] && [ -n "$version_asked" ]; then
  say "Updated to $version"
elif [ "$existing" = 1 ]; then
  say "Keelson $version is running."
else
  say "Installed Keelson $version"
fi
say ""
say "  Open:   $url"
if [ -n "$token_line" ]; then
  say "  Token:  ${token_line#Keelson setup token: }"
  say ""
  say "Next:"
  say "  1. Open the address above. The first page asks for the token and for a password."
  say "  2. Download your recovery file when it offers it and keep it somewhere safe, apart from this server."
  say "     It holds the master key; without it a lost data volume cannot be read again."
  say "  3. Then add your first server (Servers, Add server). The command it shows carries this dashboard's address,"
  say "     so the server must be able to open that address:"
  say "       - same machine as this dashboard: it works as is."
  say "       - another machine: first re-run this script with --domain keelson.example.com (or put the dashboard"
  say "         behind your own public https address). An SSH tunnel is not enough for that."
else
  say ""
  say "No setup token in the log: Keelson is already set up, so sign in at the address above."
  say "(To see what it logged: cd $dir && docker compose logs dashboard)"
fi
if [ -z "$domain" ]; then
  say ""
  say "It listens on this machine only. To look around from your own computer:  ssh -L ${port:-3000}:127.0.0.1:${port:-3000} <this server>  and open $url"
  say "To connect servers on other machines, run this again with --domain keelson.example.com to serve it over HTTPS."
fi
say ""
say "Update later (back up first: Settings, Backup; a downgrade is not supported, restore the backup instead):"
say "  curl -fsSL https://github.com/$repo/releases/download/<new version>/install.sh | sudo sh -s -- --version <new version>"
say "A copy of the database is taken before each update in $dir/backups (the last 3 are kept)."
